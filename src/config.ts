/* Process page: формати, умови, права. Тексти дослівно; нерозривні пробіли ставить `typo`. */
export const typo = (s: string) =>
  s
    .replace(
      /(^|[\s(«])(в|у|з|і|й|а|о|я|та|до|за|на|по|що|як|чи|не|від|із|ви)\s/gi,
      "$1$2 ",
    )
    .replace(/(\d)\s(?=(?:год|грн|дн|доб))/g, "$1 ")
    .replace(/\s—/g, " —");

